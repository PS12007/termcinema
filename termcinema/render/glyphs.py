def coverage_for_codepoint(cp: int):
    """Return (gh, gw, mask) if `cp` is one of our block glyphs, else None.
    Used by the screenshot rasterizer."""
    return _COVERAGE.get(cp)


_COVERAGE: dict = {}
for _mask, _cp in enumerate(OCTANT_CODEPOINTS):
    _COVERAGE.setdefault(_cp, (4, 2, _mask))
for _mask, _cp in enumerate(SEXTANT_CODEPOINTS):
    _COVERAGE.setdefault(_cp, (3, 2, _mask))
_COVERAGE[0x2584] = (2, 1, 2)
_COVERAGE[0x2580] = (2, 1, 1)
_COVERAGE[0x2588] = (1, 1, 1)
_COVERAGE[0x20] = (1, 1, 0)
