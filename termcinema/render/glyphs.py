def _bits_2x4_to_braille(mask: int) -> int:
    # Braille dot numbering: 1 4 / 2 5 / 3 6 / 7 8
    dot_bits = ((0, 0x01), (1, 0x08), (2, 0x02), (3, 0x10), (4, 0x04), (5, 0x20), (6, 0x40), (7, 0x80))
    v = 0
    for bit, dot in dot_bits:
        if mask & (1 << bit):
            v |= dot
    return 0x2800 + v


BRAILLE_CODEPOINTS = tuple(_bits_2x4_to_braille(m) for m in range(256))

# The "blocks" set: only glyphs from the classic Block Elements range
# (U+2580-259F), which every modern terminal draws pixel-perfectly, on a
# 2x4 sub-pixel grid. Each mask's complement is reachable by swapping
# fg/bg, so only one of each pair is listed.
def _m(*cells):
    return sum(1 << c for c in cells)


BLOCK_SET = (
    (_m(), 0x20),                        # empty (bg only)
    (_m(0, 1, 2, 3), 0x2580),            # upper half        / lower half
    (_m(0, 2, 4, 6), 0x258C),            # left half         / right half
    (_m(0, 2), 0x2598),                  # quadrant UL       / three-quadrant
    (_m(1, 3), 0x259D),                  # quadrant UR
    (_m(4, 6), 0x2596),                  # quadrant LL
    (_m(5, 7), 0x2597),                  # quadrant LR
    (_m(0, 2, 5, 7), 0x259A),            # diagonal UL+LR    / UR+LL
    (_m(6, 7), 0x2582),                  # lower quarter     / upper 3/4
    (_m(2, 3, 4, 5, 6, 7), 0x2586),      # lower three quarters / upper quarter
)

HALF_SET = (
    (_m(), 0x20),
    (_m(0, 1), 0x2580),   # on a 1x2 grid: bit0 = top, bit1 = bottom
)


def mask_matrix(masks, n_pixels: int) -> np.ndarray:
    """(K, n_pixels) float32 0/1 matrix from integer masks."""
    masks = np.asarray(masks, dtype=np.int64)
    bits = (masks[:, None] >> np.arange(n_pixels)[None, :]) & 1
    return bits.astype(np.float32)


